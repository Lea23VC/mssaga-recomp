#!/bin/sh
# Translate SLUS_212.70 and the game's DLLs to C, compile them and link the port (build/mssaga).
# Needs disc/SLUS_212.70 and disc/game.iso (see disc/README.md).
#
#   ./build.sh            symbols -> splat -> recompiler -> gcc, everything into build/ and asm/ (both ignored)
#
# Steps: tools/symbols.py writes build/symbol_addrs.txt from the executable's SN symbol table; splat splits
# the ELF with config/slus_212.70.yaml into asm/; tools/recomp/recomp.py writes build/recomp/*.c; gcc
# compiles them into build/obj/. Linking needs the runtime (milestone 2).
set -eu
cd "$(dirname "$0")"

ELF=disc/SLUS_212.70
[ -f "$ELF" ] || { echo "missing $ELF (see disc/README.md)"; exit 1; }
if ! (cd disc && sha1sum -c ../config/SLUS_212.70.sha1 >/dev/null 2>&1); then
    echo "$ELF is not the USA executable this config is for (config/SLUS_212.70.sha1)"; exit 1
fi

if [ ! -x .venv/bin/python ] || ! .venv/bin/python -c 'import splat, rabbitizer' 2>/dev/null; then
    python3 -m venv .venv
    .venv/bin/pip install -q 'splat64[mips]' spimdisasm rabbitizer ninja-syntax pyyaml pyelftools
fi
PY=.venv/bin/python
mkdir -p build/obj

$PY -I tools/symbols.py "$ELF" build/symbol_addrs.txt
rm -rf asm
$PY -m splat split config/slus_212.70.yaml > build/splat.log 2>&1 || { tail -20 build/splat.log; exit 1; }
RECOMP_TABLE=game_functab $PY tools/recomp/recomp.py "$ELF" build/recomp asm/text.s

CFLAGS="-O1 -g -w -fno-strict-aliasing -ffp-contract=off -march=x86-64-v2 -Iport/runtime -Ibuild/recomp"
ls build/recomp/*.c | xargs -P"$(nproc)" -I{} sh -c \
    'o=build/obj/$(basename {} .c).o; gcc -c '"$CFLAGS"' {} -o $o || { echo "FAILED: {}"; exit 255; }'
echo "compiled $(ls build/obj/*.o | wc -l) files into build/obj/"

# the game's DLLs: extracted from the disc, translated with their addresses relative to the base they load at
ISO=disc/game.iso
[ -f "$ISO" ] || { echo "missing $ISO (see disc/README.md)"; exit 1; }
$PY -I tools/dlls.py "$ISO" build/dll/bin > build/dll.log
rm -rf build/dll/c && mkdir -p build/dll/c build/dll/obj
for b in build/dll/bin/*.bin; do
    $PY tools/recomp/recomp.py --dll "$(basename "$b" .bin)" "$b" build/dll/c build/symbol_addrs.txt build/recomp/functab.h \
        | head -1
done
{
    echo '/* generated by build.sh: the translated DLLs (port/hle/dll.c) */'
    echo '#include "r5900.h"'
    for b in build/dll/bin/*.bin; do echo "extern const DllModule dll_$(basename "$b" .bin);"; done
    echo 'const DllModule *const dll_modules[] = {'
    for b in build/dll/bin/*.bin; do echo "    &dll_$(basename "$b" .bin),"; done
    echo '};'
    echo 'const int dll_module_count = sizeof dll_modules / sizeof *dll_modules;'
} > build/dll/c/dlls.c
ls build/dll/c/*.c | xargs -P"$(nproc)" -I{} sh -c \
    'o=build/dll/obj/$(basename {} .c).o; gcc -c '"$CFLAGS"' -Ibuild/dll/c {} -o $o || { echo "FAILED: {}"; exit 255; }'
echo "compiled $(ls build/dll/obj/*.o | wc -l) DLL files into build/dll/obj/"

# shaders: GLSL -> SPIR-V (glslangValidator: Ubuntu 22.04 has no glslc) -> a header of byte arrays
mkdir -p build/shaders
for sh in port/gs/shaders/*.vert port/gs/shaders/*.frag; do
    glslangValidator -V -o "build/shaders/$(basename "$sh").spv" "$sh" > /dev/null || { echo "FAILED: $sh"; exit 1; }
done
$PY -I tools/spv2h.py build/shaders/shaders.h build/shaders/*.spv

# the port: runtime, kernel, IOP services, renderer (warnings on), linked with the translated code -> build/mssaga
SDL_CFLAGS=$(pkg-config --cflags sdl3) SDL_LIBS=$(pkg-config --libs sdl3) || { echo "SDL3 not found (pkg-config sdl3)"; exit 1; }
PORT_CFLAGS="-O2 -g -Wall -Wextra -Wno-unused-parameter -fno-strict-aliasing -ffp-contract=off -march=x86-64-v2 -D_FILE_OFFSET_BITS=64"
PORT_INC="-Iport/runtime -Iport/kernel -Iport/iop -Iport/gs -Ibuild/shaders $SDL_CFLAGS"
rm -rf build/port && mkdir -p build/port
for src in port/*.c port/runtime/*.c port/kernel/*.c port/iop/*.c port/hle/*.c port/gs/*.c; do
    echo "$src"
done | xargs -P"$(nproc)" -I{} sh -c \
    'gcc -c '"$PORT_CFLAGS $PORT_INC"' {} -o "build/port/$(echo {} | tr / _ | sed "s/\.c$/.o/")" || exit 255'
# -rdynamic: the VU1 programs compiled at run time (port/gs/vu_jit.c) call the interpreter's functions in here
LINK="gcc -rdynamic build/port/*.o build/obj/*.o build/dll/obj/*.o $SDL_LIBS -lpthread -lm -ldl"

# Two stages: build/mssaga-stage1, with no VU1 programs built in, writes the game's VU1 programs as C (--gen-vu,
# found in the executable's .data); the final build/mssaga (and build-win.sh's mssaga.exe) has them compiled in,
# so no compiler is needed at run time (Windows has none: there they were interpreted, ~36 ms a frame).
printf '%s\n' '/* generated by build.sh: no VU1 programs built in (build/mssaga-stage1) */' \
    '#include "vu_internal.h"' 'typedef struct { u64 key; int (*fn)(Vu *); } VuBuiltin;' \
    'const VuBuiltin vu_builtin[1];' 'const int vu_builtin_count = 0;' 'const u64 vu_builtin_header_hash = 0;' \
    > build/vu_empty.c
gcc -c $PORT_CFLAGS $PORT_INC build/vu_empty.c -o build/vu_empty.o
$LINK build/vu_empty.o -o build/mssaga-stage1
rm -rf build/vu && mkdir -p build/vu/obj
# only the programs the game was seen to start (config/vu_programs.txt: ids, i.e. hashes; MSSAGA_VU_IDS=file collects
# them while playing), not every place the microcode could be entered (~2,500 programs, 815 MB of C)
mkdir -p build/vu_images     # images saved while playing (MSSAGA_VU_IMAGES=build/vu_images): the game's microcode, not in git
MSSAGA_VU_PROGRAMS=config/vu_programs.txt MSSAGA_VU_IMAGES=build/vu_images build/mssaga-stage1 -q --gen-vu build/vu
ls build/vu/*.c | xargs -P2 -I{} sh -c \
    'gcc -c -O2 -w -fno-strict-aliasing -ffp-contract=off -march=x86-64-v2 '"$PORT_INC"' {} -o "build/vu/obj/$(basename {} .c).o" || exit 255'
$LINK build/vu/obj/*.o -o build/mssaga
echo "linked build/mssaga"
