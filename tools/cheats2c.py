#!/usr/bin/env python3
# The MS Saga section of the CheatDevicePS2 database (https://github.com/root670/CheatDevicePS2, GPL-3.0) as a C
# string: port/runtime/cheats_db.c. Codes for the USA release (SLUS-21270; its enable code matches the executable).
#   python3 -I tools/cheats2c.py CheatDatabase.txt > port/runtime/cheats_db.c
import sys
lines = open(sys.argv[1], encoding='utf-8', errors='replace').read().splitlines()
start = lines.index('"MS Saga-A New Dawn"')
end = next(i for i in range(start + 1, len(lines)) if lines[i].startswith('"'))
out = ['/* generated by tools/cheats2c.py from the CheatDevicePS2 database (GPL-3.0, github.com/root670/CheatDevicePS2):',
       '   the codes for MS Saga: A New Dawn (USA). Cheat codes only, nothing from the game. */',
       'const char cheats_db[] =']
for l in lines[start + 1:end]:
    out.append('    "' + l.replace('\\', '\\\\').replace('"', '\\"') + '\\n"')
out.append('    ;')
print('\n'.join(out))
