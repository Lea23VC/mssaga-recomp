#!/usr/bin/env python3
"""Write splat's symbol_addrs.txt from the executable's own SN Systems symbol table.

    tools/symbols.py disc/SLUS_212.70 build/symbol_addrs.txt

SLUS_212.70 has no .symtab, but `.sndata` (0x385080, symbol `sn_dll_header_root`) holds the `SNR1` export table
SN's DLL system links the game's DLLs against: {name address, value, info} records, 12 bytes each
(docs/recon.md). The output is made from the player's disc at build time and stays out of git.
Symbols in .text become `type:func`; the others are data. Addresses with two names keep one.
"""
import struct
import sys

LOAD_OFF, BASE = 0x1000, 0x100000      # PT_LOAD: file offset 0x1000 -> 0x100000
TEXT_END = 0x285290
IMAGE_END = 0x726A00                   # end of .bss
SNR1 = 0x385080
DROP = {"ENTRYPOINT", "end",             # aliases of _start and _end
        "_stack_size"}                 # a linker constant (0x100000), not an address


def main():
    raw = open(sys.argv[1], "rb").read()
    off = lambda a: LOAD_OFF + a - BASE
    magic, _rel, _nrel, sym, nsym = struct.unpack_from("<4sIIII", raw, off(SNR1))
    assert magic == b"SNR1", magic
    names = {}
    for i in range(nsym):
        name_at, value, _info = struct.unpack_from("<III", raw, off(sym) + 12 * i)
        o = off(name_at)
        name = raw[o:raw.index(b"\0", o)].decode()
        if not BASE <= value < IMAGE_END or name in DROP:
            continue
        old = names.get(value)
        if old is None or (old.startswith("_") and not name.startswith("_")):
            names[value] = name
    with open(sys.argv[2], "w") as f:
        f.write("// generated by tools/symbols.py from the executable's SNR1 table: do not commit\n")
        for value, name in sorted(names.items()):
            kind = " // type:func" if value < TEXT_END else ""
            f.write(f"{name} = 0x{value:08X};{kind}\n")
    print(f"{len(names)} symbols -> {sys.argv[2]}")


main()
